    private fun enroll(installId: String) {
        val token = tokenInput.text.toString().trim()
        if (!token.matches(Regex("[a-f0-9]{64}"))) { toast("Paste the 64-character one-time code from your owner dashboard."); return }
        thread {
            try {
                val info = JSONObject().put("manufacturer", Build.MANUFACTURER).put("model", Build.MODEL)
                    .put("androidVersion", Build.VERSION.RELEASE).put("appVersion", "0.3.0")
                val response = post(JSONObject() .put("action", "device_redeem").put("token", token.lowercase())
                    .put("installId", installId).put("consent", true).put("deviceInfo", info))
                prefs.edit().putString("device_id", response.getString("deviceId"))
                    .putString("device_label", response.optString("label", "My Android")).apply()
                DeviceSecrets.save(this, response.getString("sessionSecret"))
                runOnUiThread {
                    tokenInput.setText("")
                    toast("Device enrolled successfully.")
                    showStatus(installId)
                    status.text = "ENROLLED • Server accepted this device. Starting visible protection…"
                    startRecoveryService()
                }
            } catch (e: Exception) { runOnUiThread { val message = e.message ?: e.javaClass.simpleName; status.text = "ENROLLMENT FAILED • $message"; toast("Enrollment failed: $message") } }
        }
    }

    private fun startRecoveryService() {
        if (!prefs.contains("device_id") || DeviceSecrets.read(this).isNullOrBlank()) { toast("Enroll this device first."); status.text = "NOT ENROLLED • Generate a one-time code in the owner dashboard and enroll this device."; return }
        try {
            ContextCompat.startForegroundService(this, Intent(this, RecoveryService::class.java))
            status.text = "Protection requested. Waiting for first server heartbeat…"
        } catch (e: Exception) {
            status.text = "PROTECTION FAILED • ${e.message ?: e.javaClass.simpleName}"
            toast("Could not start protection: ${e.message}")
        }
    }

    private fun requestLocation() {
        if (!hasLocationPermission()) {
            ActivityCompat.requestPermissions(this, arrayOf(Manifest.permission.ACCESS_FINE_LOCATION, Manifest.permission.ACCESS_COARSE_LOCATION), locationRequestCode)
        } else shareFreshLocation()
    }

    private fun hasLocationPermission(): Boolean =
        ContextCompat.checkSelfPermission(this, Manifest.permission.ACCESS_FINE_LOCATION) == PackageManager.PERMISSION_GRANTED ||
        ContextCompat.checkSelfPermission(this, Manifest.permission.ACCESS_COARSE_LOCATION) == PackageManager.PERMISSION_GRANTED

    @Suppress("MissingPermission")
    private fun shareFreshLocation() {
        val manager = getSystemService(LOCATION_SERVICE) as LocationManager
        val provider = when {
            manager.isProviderEnabled(LocationManager.GPS_PROVIDER) -> LocationManager.GPS_PROVIDER
            manager.isProviderEnabled(LocationManager.NETWORK_PROVIDER) -> LocationManager.NETWORK_PROVIDER
            else -> { toast("Turn on device location, then try again."); return }
        }
        toast("Requesting a fresh location fix…")
        var completed = false
        val listener = object : LocationListener {
            override fun onLocationChanged(location: Location) {
                if (completed) return
                completed = true
                handler.removeCallbacksAndMessages(null)
                try { manager.removeUpdates(this) } catch (_: Exception) {}
                uploadLocation(location)
            }
        }
        locationListener = listener
        try {
            manager.requestSingleUpdate(provider, listener, Looper.getMainLooper())
            handler.postDelayed({
                if (!completed) {
                    completed = true
                    try { manager.removeUpdates(listener) } catch (_: Exception) {}
                    toast("No fresh GPS fix received. Move near a window or try again outdoors.")
                }
            }, 30000L)
        } catch (e: Exception) {
            toast("Location request failed: ${e.message}")
        }
    }

    private fun uploadLocation(loc: Location) {
        thread {
            try {
                val id = prefs.getString("device_id", null) ?: throw Exception("Device is not enrolled.")
                val secret = DeviceSecrets.read(this) ?: throw Exception("Secure device session is unavailable. Re-enroll this device.")
                post(JSONObject().put("action", "device_location").put("deviceId", id).put("sessionSecret", secret)
                    .put("latitude", loc.latitude).put("longitude", loc.longitude).put("accuracy", loc.accuracy))
                runOnUiThread { toast("Fresh location shared. Reported accuracy: ±${loc.accuracy.toInt()} m") }
            } catch (e: Exception) { runOnUiThread { toast("Location not shared: ${e.message}") } }
        }
    }

    private fun showStatus(installId: String) {
        val bm = getSystemService(BATTERY_SERVICE) as BatteryManager
        val battery = bm.getIntProperty(BatteryManager.BATTERY_PROPERTY_CAPACITY)
        val cm = getSystemService(CONNECTIVITY_SERVICE) as ConnectivityManager
        val caps = cm.activeNetwork?.let { cm.getNetworkCapabilities(it) }
        val network = when {
            caps == null -> "Offline"
            caps.hasTransport(NetworkCapabilities.TRANSPORT_WIFI) -> "Wi-Fi"
            caps.hasTransport(NetworkCapabilities.TRANSPORT_CELLULAR) -> "Mobile data"
            else -> "Connected"
        }
        status.text = "Install ID: ${installId.take(8)}…\nDevice: ${Build.MANUFACTURER} ${Build.MODEL}\nAndroid: ${Build.VERSION.RELEASE}\nBattery: ${battery}%\nNetwork: ${network}\nEnrollment: ${if (prefs.contains("device_id")) "Enrolled" else "Not enrolled"}\nHeartbeat: visible foreground service"
    }

    private fun post(body: JSONObject): JSONObject {
        val conn = (URL(API).openConnection() as HttpURLConnection).apply {
            requestMethod = "POST"; connectTimeout = 15000; readTimeout = 15000; doOutput = true
            setRequestProperty("Content-Type", "application/json"); setRequestProperty("apikey", KEY)
        }
        conn.outputStream.use { it.write(body.toString().toByteArray(Charsets.UTF_8)) }
        val stream = if (conn.responseCode in 200..299) conn.inputStream else conn.errorStream
        val result = stream.bufferedReader().use { it.readText() }
        if (conn.responseCode !in 200..299) throw Exception(JSONObject(result).optString("error", "HTTP ${conn.responseCode}"))
        conn.disconnect()
        return JSONObject(result)
    }

    private fun toast(message: String) = Toast.makeText(this, message, Toast.LENGTH_LONG).show()

    override fun onRequestPermissionsResult(requestCode: Int, permissions: Array<out String>, grantResults: IntArray) {
        super.onRequestPermissionsResult(requestCode, permissions, grantResults)
        if (requestCode == locationRequestCode && hasLocationPermission()) shareFreshLocation()
        else if (requestCode == locationRequestCode) toast("Location permission was not granted.")
    }

    override fun onDestroy() {
        locationListener?.let { try { (getSystemService(LOCATION_SERVICE) as LocationManager).removeUpdates(it) } catch (_: Exception) {} }
        handler.removeCallbacksAndMessages(null)
        super.onDestroy()
    }
